CREATE TABLE CATEGORY (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODE           VARCHAR2(50 CHAR) NOT NULL,
    NAME           VARCHAR2(150 CHAR) NOT NULL,
    SORT_ORDER     NUMBER(10) DEFAULT 0 NOT NULL,
    IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CATEGORY PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORY_CODE UNIQUE (CODE),
    CONSTRAINT CK_CATEGORY_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE TOPIC (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_ID    NUMBER(19) NOT NULL,
    CODE           VARCHAR2(50 CHAR) NOT NULL,
    SLUG           VARCHAR2(100 CHAR) NOT NULL,
    NAME           VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPTION    VARCHAR2(500 CHAR),
    ICON_SVG       CLOB NOT NULL,
    STATUS         VARCHAR2(30 CHAR) DEFAULT 'COMING_SOON' NOT NULL,
    SORT_ORDER     NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TOPIC PRIMARY KEY (ID),
    CONSTRAINT UQ_TOPIC_CODE UNIQUE (CODE),
    CONSTRAINT UQ_TOPIC_SLUG UNIQUE (SLUG),
    CONSTRAINT FK_TOPIC_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORY (ID),
    CONSTRAINT CK_TOPIC_STATUS
        CHECK (STATUS IN ('AVAILABLE', 'COMING_SOON', 'HIDDEN'))
);

CREATE INDEX IX_TOPIC_CATEGORY
    ON TOPIC (CATEGORY_ID, SORT_ORDER);
