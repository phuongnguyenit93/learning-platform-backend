CREATE TABLE LEARNING_PLATFORM.TOPIC_GROUP (
                                               ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                               TOPIC_ID NUMBER(19) NOT NULL,

                                               GROUP_NAME VARCHAR2(200 CHAR) NOT NULL,

                                               SLUG VARCHAR2(150 CHAR) NOT NULL,

                                               PARENT_GROUP_ID NUMBER(19),

                                               SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,

                                               IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                               CONSTRAINT PK_TOPIC_GROUP
                                                   PRIMARY KEY (ID),

                                               CONSTRAINT UQ_TG_TOPIC_SLUG
                                                   UNIQUE (TOPIC_ID, SLUG),

                                               CONSTRAINT FK_TG_TOPIC
                                                   FOREIGN KEY (TOPIC_ID)
                                                       REFERENCES LEARNING_PLATFORM.TOPIC(ID),

                                               CONSTRAINT FK_TG_PARENT
                                                   FOREIGN KEY (PARENT_GROUP_ID)
                                                       REFERENCES LEARNING_PLATFORM.TOPIC_GROUP(ID),

                                               CONSTRAINT CK_TG_ACTIVE
                                                   CHECK (IS_ACTIVE IN (0, 1)),

                                               CONSTRAINT CK_TG_NOT_SELF_PARENT
                                                   CHECK (
                                                       PARENT_GROUP_ID IS NULL
                                                           OR PARENT_GROUP_ID <> ID
                                                       )
);

CREATE INDEX LEARNING_PLATFORM.IX_TG_TOPIC_PARENT_SORT
    ON LEARNING_PLATFORM.TOPIC_GROUP
        (TOPIC_ID, PARENT_GROUP_ID, SORT_ORDER);
