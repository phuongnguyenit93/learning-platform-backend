CREATE TABLE LEARNING_PLATFORM.MODULE_KNOWLEDGE (
                                                    ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                                    MENU_ID NUMBER(19) NOT NULL,

                                                    MENU_NODE_TYPE VARCHAR2(20 CHAR)
        DEFAULT 'SECTION' NOT NULL,

                                                    DIFFICULT VARCHAR2(20 CHAR),

                                                    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                                    CONSTRAINT PK_MODULE_KNOWLEDGE
                                                        PRIMARY KEY (ID),

                                                    CONSTRAINT UQ_MK_MENU
                                                        UNIQUE (MENU_ID),

                                                    CONSTRAINT CK_MK_MENU_TYPE
                                                        CHECK (MENU_NODE_TYPE = 'SECTION'),

                                                    CONSTRAINT CK_MK_DIFFICULT
                                                        CHECK (DIFFICULT IN (
                                                                             'BASIC',
                                                                             'INTERMEDIATE',
                                                                             'ADVANCED'
                                                            )),

                                                    CONSTRAINT FK_MK_MENU
                                                        FOREIGN KEY (MENU_ID, MENU_NODE_TYPE)
                                                            REFERENCES LEARNING_PLATFORM.MODULE_MENU(ID, NODE_TYPE),

                                                    CONSTRAINT CK_MK_ACTIVE
                                                        CHECK (IS_ACTIVE IN (0, 1))
);