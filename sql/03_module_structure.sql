-- This file is NOT executed by Spring Boot; Hibernate ddl-auto stays 'none'.
-- A Topic owns its own tree. Node keys and slugs are globally unique.
-- Existing production data/schema must be reviewed before running CREATE.

CREATE TABLE MODULE_STRUCTURE (
    ID_STRUCTURE     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    TOPIC_ID         NUMBER(19) NOT NULL,
    NODE_KEY         VARCHAR2(150 CHAR) NOT NULL,
    PARENT_NODE_KEY  VARCHAR2(150 CHAR),
    NODE_TYPE        VARCHAR2(20 CHAR) NOT NULL,
    SLUG             VARCHAR2(200 CHAR) NOT NULL,
    NAME             VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION      VARCHAR2(1000 CHAR),
    SORT_ORDER       NUMBER(10) DEFAULT 0 NOT NULL,
    IS_ACTIVE        NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_MODULE_STRUCTURE PRIMARY KEY (ID_STRUCTURE),
    CONSTRAINT FK_MS_TOPIC FOREIGN KEY (TOPIC_ID) REFERENCES TOPIC (ID),
    CONSTRAINT UQ_MS_NODE_KEY UNIQUE (NODE_KEY),
    CONSTRAINT UQ_MS_SLUG UNIQUE (SLUG),

    -- Redundant with globally unique NODE_KEY, but needed to constrain
    -- parents to the SAME TOPIC through a composite foreign key.
    CONSTRAINT UQ_MS_TOPIC_NODE UNIQUE (TOPIC_ID, NODE_KEY),
    CONSTRAINT FK_MS_PARENT FOREIGN KEY (TOPIC_ID, PARENT_NODE_KEY)
        REFERENCES MODULE_STRUCTURE (TOPIC_ID, NODE_KEY)
        DEFERRABLE INITIALLY IMMEDIATE,

    CONSTRAINT CK_MS_TYPE CHECK (NODE_TYPE IN ('GROUP', 'MODULE')),
    CONSTRAINT CK_MS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_MS_NOT_OWN_PARENT CHECK (
        PARENT_NODE_KEY IS NULL OR PARENT_NODE_KEY <> NODE_KEY
    )
);

-- Read tree nodes by TOPIC_ID, then reconstruct children by PARENT_NODE_KEY.
CREATE INDEX IX_MS_TOPIC_PARENT_SORT
    ON MODULE_STRUCTURE (TOPIC_ID, PARENT_NODE_KEY, SORT_ORDER, ID_STRUCTURE);

