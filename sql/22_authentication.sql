-- Run once as schema owner LEARNING_PLATFORM. Never run from the app at startup.
-- Google 'sub', not email, is the permanent external identity.
CREATE TABLE APP_USER (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    GOOGLE_SUB VARCHAR2(255 CHAR) NOT NULL,
    EMAIL VARCHAR2(320 CHAR),
    EMAIL_VERIFIED NUMBER(1,0) DEFAULT 0 NOT NULL,
    DISPLAY_NAME VARCHAR2(255 CHAR),
    AVATAR_URL VARCHAR2(1024 BYTE),
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_LOGIN_AT TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT APP_USER_PK PRIMARY KEY (ID),
    CONSTRAINT APP_USER_GOOGLE_SUB_UK UNIQUE (GOOGLE_SUB),
    CONSTRAINT APP_USER_EMAIL_VERIFIED_CK CHECK (EMAIL_VERIFIED IN (0,1)),
    CONSTRAINT APP_USER_STATUS_CK CHECK (STATUS IN ('ACTIVE','DISABLED'))
);

CREATE TABLE APP_ROLE (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    CODE VARCHAR2(32 CHAR) NOT NULL,
    CONSTRAINT APP_ROLE_PK PRIMARY KEY (ID),
    CONSTRAINT APP_ROLE_CODE_UK UNIQUE (CODE)
);

CREATE TABLE APP_USER_ROLE (
    USER_ID NUMBER(19,0) NOT NULL,
    ROLE_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT APP_USER_ROLE_PK PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT APP_USER_ROLE_USER_FK FOREIGN KEY (USER_ID) REFERENCES APP_USER(ID) ON DELETE CASCADE,
    CONSTRAINT APP_USER_ROLE_ROLE_FK FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLE(ID) ON DELETE CASCADE
);

CREATE INDEX APP_USER_ROLE_ROLE_IX ON APP_USER_ROLE (ROLE_ID);

