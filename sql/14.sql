CREATE TABLE LEARNING_PLATFORM.MODULE_REFERENCE (
                                                    ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                                    MODULE_ID NUMBER(19) NOT NULL,

                                                    URL VARCHAR2(2000 CHAR) NOT NULL,

                                                    SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,

                                                    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                                    CONSTRAINT PK_MODULE_REFERENCE
                                                        PRIMARY KEY (ID),

                                                    CONSTRAINT FK_MREF_MODULE
                                                        FOREIGN KEY (MODULE_ID)
                                                            REFERENCES LEARNING_PLATFORM.MODULE(ID),

                                                    CONSTRAINT CK_MREF_ACTIVE
                                                        CHECK (IS_ACTIVE IN (0, 1))
);

CREATE INDEX LEARNING_PLATFORM.IX_MREF_MODULE_SORT
    ON LEARNING_PLATFORM.MODULE_REFERENCE (
                                           MODULE_ID,
                                           SORT_ORDER,
                                           ID
        );