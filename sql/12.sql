CREATE TABLE LEARNING_PLATFORM.MODULE_ROADMAP (
                                                  ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                                  MODULE_ID NUMBER(19) NOT NULL,

                                                  ROADMAP_KEY VARCHAR2(150 CHAR) NOT NULL,

                                                  SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,

                                                  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                                  CONSTRAINT PK_MODULE_ROADMAP
                                                      PRIMARY KEY (ID),

                                                  CONSTRAINT FK_MR_MODULE
                                                      FOREIGN KEY (MODULE_ID)
                                                          REFERENCES LEARNING_PLATFORM.MODULE(ID),

                                                  CONSTRAINT UQ_MR_MODULE_KEY
                                                      UNIQUE (MODULE_ID, ROADMAP_KEY),

                                                  CONSTRAINT CK_MR_ACTIVE
                                                      CHECK (IS_ACTIVE IN (0, 1))
);

CREATE INDEX LEARNING_PLATFORM.IX_MR_MODULE_SORT
    ON LEARNING_PLATFORM.MODULE_ROADMAP (
                                         MODULE_ID,
                                         SORT_ORDER,
                                         ID
        );
