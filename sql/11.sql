CREATE TABLE LEARNING_PLATFORM.TOPIC_GROUP_MODULE (
                                                      ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                                      GROUP_ID NUMBER(19),

                                                      TOPIC_ID NUMBER(19),

                                                      MODULE_ID NUMBER(19) NOT NULL,

                                                      SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,

                                                      IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                                      CONSTRAINT PK_TGM
                                                          PRIMARY KEY (ID),

                                                      CONSTRAINT FK_TGM_GROUP
                                                          FOREIGN KEY (GROUP_ID)
                                                              REFERENCES LEARNING_PLATFORM.TOPIC_GROUP(ID),

                                                      CONSTRAINT FK_TGM_TOPIC
                                                          FOREIGN KEY (TOPIC_ID)
                                                              REFERENCES LEARNING_PLATFORM.TOPIC(ID),

                                                      CONSTRAINT FK_TGM_MODULE
                                                          FOREIGN KEY (MODULE_ID)
                                                              REFERENCES LEARNING_PLATFORM.MODULE(ID),

                                                      CONSTRAINT UQ_TGM_MODULE
                                                          UNIQUE (MODULE_ID),

                                                      CONSTRAINT CK_TGM_ACTIVE
                                                          CHECK (IS_ACTIVE IN (0, 1)),

                                                      CONSTRAINT CK_TGM_PLACEMENT
                                                          CHECK (
                                                              (GROUP_ID IS NOT NULL AND TOPIC_ID IS NULL)
                                                                  OR
                                                              (GROUP_ID IS NULL AND TOPIC_ID IS NOT NULL)
                                                              )
);

CREATE INDEX LEARNING_PLATFORM.IX_TGM_GROUP_SORT
    ON LEARNING_PLATFORM.TOPIC_GROUP_MODULE
        (GROUP_ID, SORT_ORDER);

CREATE INDEX LEARNING_PLATFORM.IX_TGM_TOPIC_SORT
    ON LEARNING_PLATFORM.TOPIC_GROUP_MODULE
        (TOPIC_ID, SORT_ORDER);