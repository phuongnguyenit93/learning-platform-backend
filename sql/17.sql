CREATE TABLE LEARNING_PLATFORM.MODULE_MENU (
                                               ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                               MODULE_ID NUMBER(19),

                                               MENU_PARENT_ID NUMBER(19),

                                               NODE_TYPE VARCHAR2(20 CHAR) NOT NULL,

                                               MENU_PARENT_TYPE VARCHAR2(20 CHAR),

                                               SLUG VARCHAR2(150 CHAR) NOT NULL,

                                               SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,

                                               IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                               CONSTRAINT PK_MODULE_MENU
                                                   PRIMARY KEY (ID),

                                               CONSTRAINT UQ_MM_ID_TYPE
                                                   UNIQUE (ID, NODE_TYPE),

                                               CONSTRAINT FK_MM_MODULE
                                                   FOREIGN KEY (MODULE_ID)
                                                       REFERENCES LEARNING_PLATFORM.MODULE(ID),

                                               CONSTRAINT FK_MM_PARENT
                                                   FOREIGN KEY (MENU_PARENT_ID, MENU_PARENT_TYPE)
                                                       REFERENCES LEARNING_PLATFORM.MODULE_MENU(ID, NODE_TYPE),

                                               CONSTRAINT CK_MM_TYPE
                                                   CHECK (NODE_TYPE IN ('CHAPTER', 'SECTION')),

                                               CONSTRAINT CK_MM_ACTIVE
                                                   CHECK (IS_ACTIVE IN (0, 1)),

                                               CONSTRAINT CK_MM_HIERARCHY
                                                   CHECK (
                                                       (
                                                           NODE_TYPE = 'CHAPTER'
                                                               AND MODULE_ID IS NOT NULL
                                                               AND MENU_PARENT_ID IS NULL
                                                               AND MENU_PARENT_TYPE IS NULL
                                                           )
                                                           OR
                                                       (
                                                           NODE_TYPE = 'SECTION'
                                                               AND MODULE_ID IS NULL
                                                               AND MENU_PARENT_ID IS NOT NULL
                                                               AND MENU_PARENT_TYPE = 'CHAPTER'
                                                           )
                                                       )
);

-- Truy vấn chapter theo module
CREATE INDEX LEARNING_PLATFORM.IX_MM_MODULE_SORT
    ON LEARNING_PLATFORM.MODULE_MENU (
                                      MODULE_ID, SORT_ORDER, ID
        );

-- Truy vấn section theo chapter
CREATE INDEX LEARNING_PLATFORM.IX_MM_PARENT_SORT
    ON LEARNING_PLATFORM.MODULE_MENU (
                                      MENU_PARENT_ID, SORT_ORDER, ID
        );

-- Chapter slug duy nhất trong một module
CREATE UNIQUE INDEX LEARNING_PLATFORM.UX_MM_CHAPTER_SLUG
    ON LEARNING_PLATFORM.MODULE_MENU (
                                      CASE WHEN NODE_TYPE = 'CHAPTER' THEN MODULE_ID END,
                                      CASE WHEN NODE_TYPE = 'CHAPTER' THEN SLUG END
        );

-- Section slug duy nhất trong cùng chapter
CREATE UNIQUE INDEX LEARNING_PLATFORM.UX_MM_SECTION_SLUG
    ON LEARNING_PLATFORM.MODULE_MENU (
                                      CASE WHEN NODE_TYPE = 'SECTION' THEN MENU_PARENT_ID END,
                                      CASE WHEN NODE_TYPE = 'SECTION' THEN SLUG END
        );