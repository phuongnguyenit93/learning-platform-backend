-- Localized, read-only Reference links: one row per reference item.
-- Prerequisites: 03_module_structure.sql and 04_language.sql.
-- Run manually as Oracle schema owner. Spring Boot ddl-auto is 'none'.
-- No URL/business-key uniqueness or composite primary key is required.

CREATE TABLE MODULE_REFERENCE (
    ID_REFERENCE  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_STRUCTURE  NUMBER(19) NOT NULL,
    LANGUAGE_CODE VARCHAR2(10 CHAR) NOT NULL,
    TITLE         VARCHAR2(300 CHAR) NOT NULL,
    URL           VARCHAR2(2000 CHAR) NOT NULL,
    DESCRIPTION   VARCHAR2(1000 CHAR),
    SORT_ORDER    NUMBER(10) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_MODULE_REFERENCE PRIMARY KEY (ID_REFERENCE),
    CONSTRAINT FK_MREF_STRUCTURE FOREIGN KEY (ID_STRUCTURE)
        REFERENCES MODULE_STRUCTURE (ID_STRUCTURE),
    CONSTRAINT FK_MREF_LANGUAGE FOREIGN KEY (LANGUAGE_CODE)
        REFERENCES LANGUAGE (CODE)
);

-- One module + language lookup; stable ordering even when SORT_ORDER repeats.
CREATE INDEX IX_MREF_MODULE_LANG_SORT
    ON MODULE_REFERENCE (ID_STRUCTURE, LANGUAGE_CODE, SORT_ORDER, ID_REFERENCE);

