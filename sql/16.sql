CREATE TABLE LEARNING_PLATFORM.MODULE_OVERVIEW (
                                                   ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                                                   MODULE_ID NUMBER(19) NOT NULL,
                                                   LANGUAGE_CODE VARCHAR2(10 CHAR) NOT NULL,
                                                   CONTENT CLOB NOT NULL,

                                                   CONSTRAINT PK_MODULE_OVERVIEW PRIMARY KEY (ID),

                                                   CONSTRAINT UQ_MO_MODULE_LANGUAGE
                                                       UNIQUE (MODULE_ID, LANGUAGE_CODE),

                                                   CONSTRAINT FK_MO_MODULE
                                                       FOREIGN KEY (MODULE_ID)
                                                           REFERENCES LEARNING_PLATFORM.MODULE(ID),

                                                   CONSTRAINT FK_MO_LANGUAGE
                                                       FOREIGN KEY (LANGUAGE_CODE)
                                                           REFERENCES LEARNING_PLATFORM.LANGUAGE(CODE)
);