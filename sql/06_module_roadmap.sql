-- One row per localized Roadmap milestone, not one row per Roadmap document.
-- Prerequisites: 03_module_structure.sql and 04_language.sql.
-- Run manually ONCE as the Oracle schema owner; Spring Boot does not apply this DDL.
-- No MILESTONE_KEY and no composite primary key: ID_ROADMAP is the only identifier.
-- Importers must replace/maintain rows by module + language when reloading YAML.

CREATE TABLE MODULE_ROADMAP (
    ID_ROADMAP    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_STRUCTURE  NUMBER(19) NOT NULL,
    LANGUAGE_CODE VARCHAR2(10 CHAR) NOT NULL,
    TITLE         VARCHAR2(300 CHAR) NOT NULL,
    PURPOSE       VARCHAR2(1000 CHAR) NOT NULL,
    OBJECTIVE     VARCHAR2(2000 CHAR),
    SORT_ORDER    NUMBER(10) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_MODULE_ROADMAP PRIMARY KEY (ID_ROADMAP),
    CONSTRAINT FK_MR_STRUCTURE FOREIGN KEY (ID_STRUCTURE)
        REFERENCES MODULE_STRUCTURE (ID_STRUCTURE),
    CONSTRAINT FK_MR_LANGUAGE FOREIGN KEY (LANGUAGE_CODE)
        REFERENCES LANGUAGE (CODE)
);

-- Efficient lookup of one module's localized milestones in display order.
-- Equal SORT_ORDER values are allowed; ID_ROADMAP breaks ties deterministically.
CREATE INDEX IX_MR_MODULE_LANG_SORT
    ON MODULE_ROADMAP (ID_STRUCTURE, LANGUAGE_CODE, SORT_ORDER, ID_ROADMAP);

