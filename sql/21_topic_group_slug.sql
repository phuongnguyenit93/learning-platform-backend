-- Add a stable, URL-safe identifier to each Topic Group.
-- Current Group names are English ASCII; non-alphanumeric runs become one hyphen.

ALTER TABLE LEARNING_PLATFORM.TOPIC_GROUP
    ADD (SLUG VARCHAR2(150 CHAR));

UPDATE LEARNING_PLATFORM.TOPIC_GROUP
SET SLUG = TRIM(BOTH '-' FROM REGEXP_REPLACE(
    LOWER(TRIM(GROUP_NAME)),
    '[^a-z0-9]+',
    '-'
));

ALTER TABLE LEARNING_PLATFORM.TOPIC_GROUP
    MODIFY (SLUG NOT NULL);

ALTER TABLE LEARNING_PLATFORM.TOPIC_GROUP
    ADD CONSTRAINT UQ_TG_TOPIC_SLUG UNIQUE (TOPIC_ID, SLUG);
