CREATE TABLE LEARNING_PLATFORM.MODULE (
                                          ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

                                          SERVICE_NAME VARCHAR2(150 CHAR) NOT NULL,

                                          SLUG VARCHAR2(200 CHAR) NOT NULL,

                                          NAME VARCHAR2(200 CHAR) NOT NULL,

                                          SERVICE_NAME_DESCRIPTION VARCHAR2(1000 CHAR),

                                          SPECIAL_NOTE VARCHAR2(2000 CHAR),

                                          IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,

                                          CONSTRAINT PK_MODULE
                                              PRIMARY KEY (ID),

                                          CONSTRAINT UQ_MODULE_SERVICE_NAME
                                              UNIQUE (SERVICE_NAME),

                                          CONSTRAINT UQ_MODULE_SLUG
                                              UNIQUE (SLUG),

                                          CONSTRAINT CK_MODULE_ACTIVE
                                              CHECK (IS_ACTIVE IN (0, 1))
);
